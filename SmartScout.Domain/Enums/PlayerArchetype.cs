namespace SmartScout.Domain.Enums;

public enum PlayerArchetype
{
    FloorGeneral,     // High playmaking, pass-first or pick-and-roll maestro
    Sharpshooter,     // Elite 3-point floor spacer, off-ball movement
    SlashingWing,     // High-volume athletic rim slasher and wing scorer
    PaintAnchor,      // Elite rim protection, shot-blocking and paint rebounding
    PointCenter,      // Playmaking offensive hub big man (e.g., Jokic, Sabonis, Sengun)
    StretchBig,       // Big man who spaces the floor with reliable 3-point shooting
    TwoWayStar,       // All-NBA caliber impact on both offense and defense
    RolePlayer        // Balanced complementary contributor
}
